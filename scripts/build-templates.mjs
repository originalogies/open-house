// Bundles the HTML email templates into a module the functions can import.
// Run with: npm run build:templates (also runs on every Netlify build).
import fs from "node:fs";
import path from "node:path";

const dir = "open-house/emails";
const names = {
  "1-request-received.html": "requestReceived",
  "2-request-sent.html": "requestSent",
  "3-request-confirmed.html": "requestConfirmed",
  "4-open-house-reminder.html": "reminder",
};
let out = "// Generated by scripts/build-templates.mjs. Do not edit by hand.\n";
for (const [file, key] of Object.entries(names)) {
  // Drop the leading developer comment so its example {{fields}} are not rendered.
  const html = fs.readFileSync(path.join(dir, file), "utf8").replace(/<!--[\s\S]*?-->/, "");
  out += `export const ${key} = ${JSON.stringify(html)};\n`;
}
fs.writeFileSync("netlify/lib/templates.generated.mjs", out);
console.log("wrote netlify/lib/templates.generated.mjs");
